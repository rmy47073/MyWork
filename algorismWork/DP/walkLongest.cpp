#include <iostream>
#include <vector>
#include <algorithm>
using namespace std;

/*
小云计划连续 n 日户外徒步，每天可选：休息、低强度、高强度。
 - 低强度走 A[i][0] 千米
 - 高强度走 A[i][1] 千米
 - 若选高强度，则前一天必须休息（第一天除外）
目标：计算 n 天内最远总距离。

状态定义：
  dp[i][0] — 第 i 天休息，前 i 天的最大总距离
  dp[i][1] — 第 i 天低强度，前 i 天的最大总距离
  dp[i][2] — 第 i 天高强度，前 i 天的最大总距离

输入样例：
  5
  8 12
  6 13
  6 15
  5 12
  4 8
输出：36
*/
int main() {
    int n;
    cin >> n;
    vector<vector<int>> A(n, vector<int>(2));
    for (int i = 0; i < n; i++)
        cin >> A[i][0] >> A[i][1];

    // dp[i][0]=休息  dp[i][1]=低强度  dp[i][2]=高强度
    vector<vector<int>> dp(n, vector<int>(3));

    // 第 0 天，也就是第一天初始化
    dp[0][0] = 0;             // 第一天休息，走 0 km
    dp[0][1] = A[0][0];       // 第一天低强度
    dp[0][2] = A[0][1];       // 第一天高强度

    for (int i = 1; i < n; i++) {
        // 今天休息：昨天只能是低强度或高强度，不能连续两天休息浪费里程
        dp[i][0] = max(dp[i - 1][1], dp[i - 1][2]);
        // 今天低强度：昨天任意状态均可，加上今天的低强度里程
        dp[i][1] = max({dp[i - 1][0], dp[i - 1][1], dp[i - 1][2]}) + A[i][0];
        // 今天高强度：昨天必须休息，加上今天的高强度里程
        dp[i][2] = dp[i - 1][0] + A[i][1];
    }

    // 最后一天不选休息，不能增加里程，亏了里程，取低强度/高强度最大值
    cout << max(dp[n - 1][1], dp[n - 1][2]) << endl;
}
